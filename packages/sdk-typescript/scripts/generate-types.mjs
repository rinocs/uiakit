#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = resolve(packageDir, '../api-contract/public.openapi.json');
const outputPath = resolve(packageDir, 'src/generated.ts');
const checkOnly = process.argv.includes('--check');

const document = JSON.parse(readFileSync(contractPath, 'utf8'));
const schemas = document.components?.schemas ?? {};

function identifier(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : JSON.stringify(value);
}

function refName(ref) {
  const name = ref.split('/').at(-1);
  if (!name) throw new Error(`Invalid $ref: ${ref}`);
  return name;
}

function typeOf(schema, indent = 0) {
  if (!schema || Object.keys(schema).length === 0) return 'unknown';
  if (schema.$ref) return refName(schema.$ref);
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) {
    if (schema.enum.length === 0) return 'never';
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  }
  if (Array.isArray(schema.anyOf)) {
    return schema.anyOf.map((item) => typeOf(item, indent)).join(' | ');
  }
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map((item) => typeOf(item, indent)).join(' | ');
  }
  if (schema.type === 'null') return 'null';
  if (schema.type === 'array') {
    return `Array<${typeOf(schema.items ?? {}, indent)}>`;
  }
  if (
    schema.type === 'object' ||
    schema.properties !== undefined ||
    schema.additionalProperties !== undefined
  ) {
    return objectType(schema, indent);
  }
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    default:
      return 'unknown';
  }
}

function objectType(schema, indent) {
  const required = new Set(schema.required ?? []);
  const properties = schema.properties ?? {};
  const lines = [];
  for (const [name, property] of Object.entries(properties)) {
    lines.push(
      `${' '.repeat(indent + 2)}${identifier(name)}${
        required.has(name) ? '' : '?'
      }: ${typeOf(property, indent + 2)};`,
    );
  }
  if (schema.additionalProperties === true) {
    lines.push(`${' '.repeat(indent + 2)}[key: string]: unknown;`);
  } else if (
    schema.additionalProperties &&
    typeof schema.additionalProperties === 'object'
  ) {
    lines.push(
      `${' '.repeat(indent + 2)}[key: string]: ${typeOf(
        schema.additionalProperties,
        indent + 2,
      )};`,
    );
  }
  if (lines.length === 0) {
    return schema.additionalProperties === false
      ? 'Record<string, never>'
      : 'Record<string, unknown>';
  }
  return `{\n${lines.join('\n')}\n${' '.repeat(indent)}}`;
}

const chunks = [
  '// Generated by scripts/generate-types.mjs from packages/api-contract/public.openapi.json.',
  '// Do not edit by hand. Run `npm run generate` in packages/sdk-typescript.',
  '',
];

for (const name of Object.keys(schemas).sort()) {
  const schema = schemas[name];
  const isInterface =
    schema.type === 'object' &&
    Object.keys(schema.properties ?? {}).length > 0 &&
    schema.additionalProperties !== true &&
    !schema.anyOf &&
    !schema.oneOf &&
    !schema.enum &&
    !schema.$ref;
  chunks.push(
    isInterface
      ? `export interface ${name} ${typeOf(schema, 0)}`
      : `export type ${name} = ${typeOf(schema, 0)};`,
    '',
  );
}

const output = `${chunks.join('\n').trimEnd()}\n`;
const current = (() => {
  try {
    return readFileSync(outputPath, 'utf8');
  } catch {
    return null;
  }
})();

if (checkOnly) {
  if (current !== output) {
    console.error(
      'src/generated.ts is out of date; run `npm run generate` in packages/sdk-typescript.',
    );
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(outputPath, output);
console.log(`Generated ${Object.keys(schemas).length} types in src/generated.ts`);
